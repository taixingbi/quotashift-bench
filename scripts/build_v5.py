"""Generate every protocol-v5 scenario YAML from ONE spec (docs/PROTOCOL_V5_DRAFT.md), so fixed settings are identical.

    uv run python scripts/build_v5.py            # writes experiments/v5/**.yaml (refuses to overwrite)
    uv run python scripts/build_v5.py --check    # exit 1 if the files on disk differ from the spec

DRAFT until the v5 freeze commit. Sizes are REAL Qwen2.5 tokens (prompt_token_unit: tokenizer; ignore_eos: true).
The only serving parameter that differs between files is the gateway cap C (safety.max_global_inflight); it is
identical in the attack and control arm of every file. Direct-vLLM files carry C = 8 for schema identity with v4 but
the cap is NOT applied on --path direct (the harness backend cap is 512).
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
V5 = REPO / "experiments" / "v5"

RUNTIME = 120
SEED0 = 5000             # main seeds 5000..5009 (disjoint from v4 42..46 / 900 / 1000)
REPS = 10
SMOKE_SEED = 4900
CAPS = (8, 16, 32)
SHAPES = {"P": (1024, 32), "D": (64, 256), "S": (64, 64)}
PER_REQ_CAPS = (1024, 256)
THRESHOLD = 1.25
# (comparison, attack shape, control) per stage; Stage B (L = 400) drops P vs S (v4 calibration: S/D at L400 were
# execution-feasible but over the saturation limit at C = 8; P was not probed beyond L200 in R1)
COMPARISONS = {"aa_ind": ("S", "independent_replicate"), "decode_vs_short": ("D", "token_matched_fixed"),
               "prefill_vs_short": ("P", "token_matched_fixed")}
STAGES = {"A": (200, ("aa_ind", "decode_vs_short", "prefill_vs_short")), "B": (400, ("aa_ind", "decode_vs_short"))}
# direct-vLLM reference: Stage A all three comparisons; Stage B D vs S only
DIRECT = {"A": ("aa_ind", "decode_vs_short", "prefill_vs_short"), "B": ("decode_vs_short",)}

HEADER = """# PROTOCOL v5 ({block}) — docs/PROTOCOL_V5_DRAFT.md. GENERATED by scripts/build_v5.py; do not edit by hand.
# {what}
# Sizes are real Qwen2.5 tokens; ignore_eos: realized output == max_tokens. Serving config is fixed across ALL v5
# files except the gateway cap C = safety.max_global_inflight ({cap_note}), which is identical in both arms.
"""


def count(shape: str, load: int, runtime: int = RUNTIME) -> int:
    i, o = SHAPES[shape]
    return max(1, round(load * runtime / (i + o)))


def scenario(*, sid: str, block: str, what: str, shape: str, load: int, control: str, cap: int, direct: bool,
             reps: int, seed: int, runtime: int = RUNTIME) -> str:
    i, o = SHAPES[shape]
    cs = (f"\n  control_shape: {{input_tokens: {SHAPES['S'][0]}, output_tokens: {SHAPES['S'][1]}}}"
          if control == "token_matched_fixed" else "")
    cap_note = "NOT applied: run with --path direct" if direct else f"C = {cap}"
    return HEADER.format(block=block, what=what, cap_note=cap_note) + f"""schema_version: 1
scenario_id: {sid}
protocol_version: 5
prompt_token_unit: tokenizer
ignore_eos: true
isolation_salt: v5-{sid}-r1
frozen_traces: ../FROZEN_TRACES.json  # experiments/v5/FROZEN_TRACES.json (scripts/freeze_v5.py --live, pre-stage P)
expect_prefix_caching: "on"
seed: {seed}
model: Qwen/Qwen2.5-7B-Instruct
model_max_len: 4096
runtime_seconds: {runtime}
endpoint: http://localhost:8080
victim_tenants: [v00, v01, v02]
competing_tenants: [comp]
budget_class: total_requests
safety:
  max_total_requests: 1500
  max_global_inflight: {cap}
  max_requests_per_tenant: 1400
  max_input_tokens_per_request: {PER_REQ_CAPS[0]}
  max_output_tokens_per_request: {PER_REQ_CAPS[1]}
  max_runtime_seconds: 240
  per_request_timeout_seconds: 120
comparison:
  primary_control: {control}
  matched_request_budget: {str(control == "independent_replicate").lower()}
  matched_token_budget: true{cs}
  feasibility_gates: classify
  repetitions: {reps}
  degradation_metric: user_ttft_mean
  effect_direction: two_sided
  preregistered_threshold: {THRESHOLD}
  budget_tolerance: 0.05
  threshold_justification: "1.25x as v4; valid only if > 2x the A/A-ind 95% half-width at the same (C, L) (PROTOCOL_V5 §6)."
benign: {{rate_rps: 0.3, request_shape: short, ttft_deadline_ms: 2000, e2e_deadline_ms: 30000}}
phases:
  - {{name: main, duration_seconds: {runtime}, pattern: steady, input_tokens: {i}, output_tokens: {o}, request_count: {count(shape, load, runtime)}}}
"""


def cell_id(comp: str, load: int, cap: int | None) -> str:
    return f"v5_{comp}_L{load}_{'direct' if cap is None else f'C{cap}'}"


def build() -> dict[Path, str]:
    files: dict[Path, str] = {}
    for stage, (load, comps) in STAGES.items():
        for comp in comps:
            shape, ctrl = COMPARISONS[comp]
            for cap in (*CAPS, None):
                if cap is None and comp not in DIRECT[stage]:
                    continue
                sid = cell_id(comp, load, cap)
                where = "direct vLLM (reference path)" if cap is None else f"FCFS gateway C = {cap}"
                files[V5 / f"stage_{stage.lower()}" / f"{sid}.yaml"] = scenario(
                    sid=sid, block=f"stage {stage}", what=f"{comp} at L={load} tok/s via {where}: attack {shape} "
                    f"{SHAPES[shape]} x {count(shape, load)}; control {ctrl}.", shape=shape, load=load, control=ctrl,
                    cap=8 if cap is None else cap, direct=cap is None, reps=REPS, seed=SEED0)
    sm = 40  # smokes: 40 s, one seed (4900), harness validation only; never analysed
    for comp, cap in (("decode_vs_short", 16), ("decode_vs_short", 32), ("aa_ind", 8), ("decode_vs_short", None)):
        shape, ctrl = COMPARISONS[comp]
        sid = f"v5_smoke_{comp}_{'direct' if cap is None else f'C{cap}'}"
        files[V5 / "smoke" / f"{sid}.yaml"] = scenario(
            sid=sid, block="smoke", what=f"smoke: {comp} at L=200 scaled to {sm} s; harness validation only, never "
            "pooled or analysed as a result.", shape=shape, load=200, control=ctrl, cap=8 if cap is None else cap,
            direct=cap is None, reps=1, seed=SMOKE_SEED, runtime=sm)
    return files


RERUN = "__r2"   # §8 rule 2: at most one rerun per block, with a new isolation salt (pre-generated, frozen with the rest)


def build_reruns(files: dict[Path, str] | None = None) -> dict[Path, str]:
    """The single permitted rerun of every block: identical to the block except scenario id (+ `__r2`), isolation salt
    (`-r2`) and a header note. Same seeds => same frozen schedule (FROZEN_SCHEDULE.json is keyed by the base id);
    traces are frozen with the rest at pre-stage P. Executed only by run_v5.sh --rerun after the block failed a gate."""
    out: dict[Path, str] = {}
    for p, t in (files if files is not None else build()).items():
        sid = p.stem
        a, b = f"scenario_id: {sid}\n", f"isolation_salt: v5-{sid}-r1\n"
        assert t.count(a) == 1 and t.count(b) == 1, sid
        note = (f"# RERUN VARIANT of {sid} (PROTOCOL_V5 §8 rule 2): the only permitted rerun; identical except the id and\n"
                f"# the isolation salt. Run only as `scripts/run_v5.sh <stage> --rerun {sid} --reason <text>` after {sid}\n"
                "# failed a gate; the failed block is kept as invalid.\n")
        out[V5 / "reruns" / f"{sid}{RERUN}.yaml"] = note + t.replace(a, f"scenario_id: {sid}{RERUN}\n").replace(
            b, f"isolation_salt: v5-{sid}-r2\n")
    return out


def base_id(sid: str) -> str:
    return sid.removesuffix(RERUN)


def path_of(p: Path) -> str:
    """--path for a generated file (the runner flag; the YAML does not carry it)."""
    return "direct" if base_id(p.stem).endswith("_direct") else "gateway"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    files = build()
    files |= build_reruns(files)
    if args.check:
        bad = [p for p, t in files.items() if not p.exists() or p.read_text() != t]
        extra = sorted(set(V5.rglob("*.yaml")) - set(files)) if V5.exists() else []
        print(f"{len(files)} files, {len(bad)} differ, {len(extra)} unexpected")
        for p in [*bad, *extra][:10]:
            print("  :", p.relative_to(REPO))
        return 1 if bad or extra else 0
    differ = [p for p, t in files.items() if p.exists() and p.read_text() != t]
    if differ:
        print(f"refusing to overwrite {len(differ)} differing v5 file(s), e.g. {differ[0]}", file=sys.stderr)
        return 3
    files = {p: t for p, t in files.items() if not p.exists()}   # only add missing files; identical ones stay
    for p, t in files.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(t)
    print(f"wrote {len(files)} files under {V5.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
