"""Generate every protocol-v4 scenario YAML from ONE spec (docs/PROTOCOL_V4.md), so fixed settings are identical.

    uv run python scripts/build_v4.py            # writes experiments/v4/**.yaml (refuses to overwrite)
    uv run python scripts/build_v4.py --check    # exit 1 if the files on disk differ from the spec

All sizes are REAL Qwen2.5 tokens (prompt_token_unit: tokenizer; ignore_eos: true => realized output = max_tokens).
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
V4 = REPO / "experiments" / "v4"

RUNTIME = 120
MAIN_SEEDS = 42          # R1/R2/R3 seeds start here (R1 5, R2 3)
CAL_SEED = 1000          # calibration traces use disjoint seeds; never analysed with the main runs
SHAPES = {"P": (1024, 32), "D": (64, 256), "S": (64, 64)}   # R1: prefill-heavy, decode-heavy, short (real tokens)
LOADS = (200, 300, 400)  # R1 calibration grid: authorized competitor tokens per second
R2F_SIZES = (96, 128, 192, 256, 512, 1024, 2048, 3584)       # R2-F: total tokens/request, output fixed at 32
R2F_BUDGET = 120_000     # authorized competitor tokens per 120 s window (1000 tok/s)
R2B_SIZES = (64, 128, 256, 512, 1024, 2048)                  # R2-B: input = output = size/2
R2B_BUDGET = 48_000      # 400 tok/s
R3_R2F_SIZES = (96, 256, 1024)  # R2-F points replayed through direct vLLM (overload / boundary / feasible)

HEADER = """# PROTOCOL v4 ({block}) — docs/PROTOCOL_V4.md. GENERATED by scripts/build_v4.py; do not edit by hand.
# {what}
# Sizes are real Qwen2.5 tokens (calibrated + verified on the live tokenizer before sending); ignore_eos: realized
# output == max_tokens. Serving config is fixed across ALL v4 files: FCFS gateway, max_global_inflight 8, 60 s gateway
# queue timeout, vLLM settings as recorded in each report's target_snapshot/.
"""


def scenario(*, sid: str, block: str, what: str, phase: dict, control: str, metric: str, direction: str,
             reps: int, seed: int, caps: tuple[int, int], matched_tokens: bool, feas: str = "enforce",
             control_shape: tuple[int, int] | None = None, runtime: int = RUNTIME, threshold: float = 1.25) -> str:
    cin, cout = caps
    cs = (f"\n  control_shape: {{input_tokens: {control_shape[0]}, output_tokens: {control_shape[1]}}}"
          if control_shape else "")
    return HEADER.format(block=block, what=what) + f"""schema_version: 1
scenario_id: {sid}
protocol_version: 4
prompt_token_unit: tokenizer
ignore_eos: true
isolation_salt: v4-{sid}-r1
frozen_traces: ../FROZEN_TRACES.json  # experiments/v4/FROZEN_TRACES.json (scripts/freeze_v4.py)
expect_prefix_caching: "on"
seed: {seed}
model: Qwen/Qwen2.5-7B-Instruct
model_max_len: 4096
runtime_seconds: {runtime}
endpoint: http://localhost:8080
victim_tenants: [v00, v01, v02]
competing_tenants: [comp]
budget_class: total_requests
safety:
  max_total_requests: 1500
  max_global_inflight: 8
  max_requests_per_tenant: 1400
  max_input_tokens_per_request: {cin}
  max_output_tokens_per_request: {cout}
  max_runtime_seconds: 240
  per_request_timeout_seconds: 120
comparison:
  primary_control: {control}
  matched_request_budget: false
  matched_token_budget: {str(matched_tokens).lower()}{cs}
  feasibility_gates: {feas}
  repetitions: {reps}
  degradation_metric: {metric}
  effect_direction: {direction}
  preregistered_threshold: {threshold}
  budget_tolerance: 0.05
  threshold_justification: "1.25x, as A7-A9 (>= 2x the A/A noise half-width; R1 re-measures it at the selected load)."
benign: {{rate_rps: 0.3, request_shape: short, ttft_deadline_ms: 2000, e2e_deadline_ms: 30000}}
phases:
  - {{name: main, duration_seconds: {runtime}, pattern: steady, input_tokens: {phase['in']}, output_tokens: {phase['out']}, request_count: {phase['n']}}}
"""


def r1_count(shape: str, load: int) -> int:
    i, o = SHAPES[shape]
    return max(1, round(load * RUNTIME / (i + o)))


def build() -> dict[Path, str]:
    files: dict[Path, str] = {}
    caps_r1 = (1024, 256)
    # calibration: each shape x load as an A/A pair (two independent replicates of the same workload), seed 1000
    for sh in SHAPES:
        for L in LOADS:
            i, o = SHAPES[sh]
            sid = f"v4_cal_{sh}_L{L}"
            files[V4 / "calibration" / f"{sid}.yaml"] = scenario(
                sid=sid, block="calibration", what=f"R1 feasibility probe: shape {sh} ({i}/{o}) at {L} authorized "
                f"competitor tok/s; A/A replicate pair; selection rule in PROTOCOL_V4 §R1.2. Not analysed as a result.",
                phase={"in": i, "out": o, "n": r1_count(sh, L)}, control="identical_workload", metric="user_ttft_p95",
                direction="two_sided", reps=1, seed=CAL_SEED, caps=caps_r1, matched_tokens=True)
    # R1 main blocks, pre-registered for every grid load (only the selected L* is run)
    for L in LOADS:
        for name, sh, ctrl in (("aa_short", "S", "identical_workload"), ("prefill_vs_short", "P", "token_matched_fixed"),
                               ("decode_vs_short", "D", "token_matched_fixed")):
            i, o = SHAPES[sh]
            sid = f"v4_r1_{name}_L{L}"
            files[V4 / "r1" / f"{sid}.yaml"] = scenario(
                sid=sid, block="r1", what=f"R1 {name} at L={L} tok/s: attack {sh} ({i}/{o}) x {r1_count(sh, L)}; control "
                f"{'identical (A/A noise floor)' if ctrl == 'identical_workload' else 'token-matched short 64/64 over the whole window'}.",
                phase={"in": i, "out": o, "n": r1_count(sh, L)}, control=ctrl, metric="user_ttft_p95",
                direction="two_sided", reps=5, seed=MAIN_SEEDS, caps=caps_r1, matched_tokens=True,
                control_shape=SHAPES["S"] if ctrl == "token_matched_fixed" else None)
    # R2 sweeps (victims-only control; feasibility gates classify the regime)
    for fam, sizes, budget, split, caps in (
            ("F", R2F_SIZES, R2F_BUDGET, lambda s: (s - 32, 32), (3584, 64)),
            ("B", R2B_SIZES, R2B_BUDGET, lambda s: (s // 2, s // 2), (1024, 1024))):
        for s in sizes:
            i, o = split(s)
            n = round(budget / s)
            sid = f"v4_r2{fam.lower()}_s{s}"
            files[V4 / "r2" / f"{sid}.yaml"] = scenario(
                sid=sid, block="r2", what=f"R2-{fam} granularity point: {n} requests of {i}/{o} tokens "
                f"(~{n * s} of a fixed {budget}-token budget per {RUNTIME} s); control = victims only.",
                phase={"in": i, "out": o, "n": n}, control="benign_only", metric="user_ttft_p95",
                direction="two_sided", reps=3, seed=MAIN_SEEDS, caps=caps, matched_tokens=False, feas="classify")
    # smokes: 40 s, seed 900, one paired seed; harness validation before any full block (never analysed)
    sm = 40
    for sid, what, phase, ctrl, caps, feas, cshape in (
            ("v4_smoke_r1_prefill_vs_short", "R1 smoke (P vs token-matched short, L=200 scaled to 40 s)",
             {"in": 1024, "out": 32, "n": round(200 * sm / 1056)}, "token_matched_fixed", caps_r1, "enforce", SHAPES["S"]),
            ("v4_smoke_r2f_s96", "R2-F smoke (s=96, overload expected; budget scaled to 40 s)",
             {"in": 64, "out": 32, "n": round(R2F_BUDGET * sm / RUNTIME / 96)}, "benign_only", (3584, 64), "classify", None),
            ("v4_smoke_r2b_s2048", "R2-B smoke (s=2048: 1024-token ignore_eos outputs, drain)",
             {"in": 1024, "out": 1024, "n": round(R2B_BUDGET * sm / RUNTIME / 2048)}, "benign_only", (1024, 1024),
             "classify", None)):
        files[V4 / "smoke" / f"{sid}.yaml"] = scenario(
            sid=sid, block="smoke", what=what + "; harness validation only, never pooled or analysed as a result.",
            phase=phase, control=ctrl, metric="user_ttft_p95", direction="two_sided", reps=1, seed=900, caps=caps,
            matched_tokens=ctrl == "token_matched_fixed", feas=feas, control_shape=cshape, runtime=sm)
    return files


def r3_variants(files: dict[Path, str]) -> dict[Path, str]:
    """Direct-vLLM replays: identical scenario except id + salt (prompt token counts are identical)."""
    out = {}
    targets = [V4 / "r1" / f"v4_r1_{n}_L{{L}}.yaml" for n in ("prefill_vs_short", "decode_vs_short")]
    for L in LOADS:
        for t in targets:
            p = Path(str(t).format(L=L))
            out[p] = files[p]
    for s in R3_R2F_SIZES:
        p = V4 / "r2" / f"v4_r2f_s{s}.yaml"
        out[p] = files[p]
    out[V4 / "smoke" / "v4_smoke_r2f_s96.yaml"] = files[V4 / "smoke" / "v4_smoke_r2f_s96.yaml"]
    res = {}
    for p, text in out.items():
        sid = p.stem
        new = text.replace(f"scenario_id: {sid}\n", f"scenario_id: {sid}_direct\n").replace(
            f"isolation_salt: v4-{sid}-r1", f"isolation_salt: v4-{sid}_direct-r1").replace(
            "# PROTOCOL v4 (", "# PROTOCOL v4 R3 direct-vLLM replay of (", 1)
        new = new.replace("queue timeout, vLLM settings", "queue timeout (NOT applied: run with --path direct), vLLM settings")
        res[(V4 / "smoke" if p.parent.name == "smoke" else V4 / "r3") / f"{sid}_direct.yaml"] = new
    return res


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    files = build()
    files.update(r3_variants(files))
    if args.check:
        bad = [p for p, t in files.items() if not p.exists() or p.read_text() != t]
        print(f"{len(files)} files, {len(bad)} differ")
        for p in bad[:10]:
            print("  differs:", p.relative_to(REPO))
        return 1 if bad else 0
    existing = [p for p in files if p.exists()]
    if existing:
        print(f"refusing to overwrite {len(existing)} existing v4 file(s), e.g. {existing[0]}", file=sys.stderr)
        return 3
    for p, t in files.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(t)
    print(f"wrote {len(files)} files under {V4.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
