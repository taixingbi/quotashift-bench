"""X2 Amendment A2 (DRAFT) main-scenario generator: the frozen build_x2 main files + the A2 arrival-law keys.

    uv run python scripts/build_x2_a2.py --platform g1m0          # -> experiments/x2_a2/g1m0/{main/, RATES.json, QUALIFICATION.json}
    uv run python scripts/build_x2_a2.py --platform g1m0 --check  # files == generator output, copies == originals

docs/PROTOCOL_X2_AMENDMENT_A2.md. Every A2 file is a pure function of the frozen generator's main output at the
platform's own committed RATES.json (experiments/x2/<p>/RATES.json, selected once under the frozen rule):

  * one header line naming the amendment is prepended;
  * `protocol_amendment: X2-A2` and `competitor_arrival_law: stratified_v1` are inserted after `protocol_version: 5`;
  * nothing else changes: ids, seeds, repetitions, caps, rates, shapes, salts, budgets, thresholds, rerun files.

The original X2 records are never written: QUALIFICATION.json and RATES.json are copied byte-for-byte (verified) into
experiments/x2_a2/<p>/ because the frozen drivers resolve them relative to the scenario root.
"""

from __future__ import annotations

import argparse
import json
import shutil
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "scripts"))
import build_x2  # noqa: E402  (frozen; read-only import)

X2 = REPO / "experiments" / "x2"
A2 = REPO / "experiments" / "x2_a2"
COPIED = ("QUALIFICATION.json", "RATES.json")
HEADER = ("# X2 AMENDMENT A2 (stratified competitor arrivals) — docs/PROTOCOL_X2_AMENDMENT_A2.md. GENERATED by "
          "scripts/build_x2_a2.py from the frozen build_x2 main output; do not edit.\n")
ANCHOR = "\nprotocol_version: 5\n"
KEYS = "\nprotocol_version: 5\nprotocol_amendment: X2-A2\ncompetitor_arrival_law: stratified_v1\n"


def amend(text: str) -> str:
    if text.count(ANCHOR) != 1:
        raise ValueError("frozen main file without exactly one 'protocol_version: 5' line")
    return HEADER + text.replace(ANCHOR, KEYS)


def build_main_a2(plat: str, rates: dict) -> dict[str, str]:
    """{relative path under experiments/x2_a2: text} for the main cells and their single-rerun files."""
    return {rel: amend(text) for rel, text in build_x2.with_reruns(build_x2.build_main(plat, rates)).items()}


def rates_of(plat: str, src: Path = X2) -> dict:
    f = src / plat / "RATES.json"
    if not f.exists():
        raise SystemExit(f"REFUSED: {f} missing (rates are selected once under the frozen rule, before A2)")
    return json.loads(f.read_text())


def check(plat: str, *, src: Path = X2, root: Path = A2) -> list[str]:
    p: list[str] = []
    for name in COPIED:
        a, b = src / plat / name, root / plat / name
        if not b.exists() or not a.exists() or a.read_bytes() != b.read_bytes():
            p.append(f"{root.name}/{plat}/{name} is not a byte copy of the original X2 record")
    gen = build_main_a2(plat, rates_of(plat, src))
    for rel, text in gen.items():
        if not (root / rel).exists() or (root / rel).read_text() != text:
            p.append(f"{rel} differs from the A2 generator")
    extra = {str(f.relative_to(root)) for f in (root / plat / "main").rglob("*.yaml")} - set(gen) \
        if (root / plat / "main").exists() else set()
    p += [f"{x}: not produced by the A2 generator" for x in sorted(extra)]
    return p


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--platform", choices=tuple(build_x2.PLATFORMS), required=True)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    if a.check:
        p = check(a.platform)
        print(f"{a.platform}: A2 files match the generator" if not p else "MISMATCH:\n  " + "\n  ".join(p))
        return 0 if not p else 1
    r = rates_of(a.platform)
    if not r.get("low_feasible", False):
        print(f"REFUSED: {a.platform} low point infeasible (reported, never substituted)", file=sys.stderr)
        return 3
    files = build_main_a2(a.platform, r)
    for rel in files:
        if (A2 / rel).exists() and (A2 / rel).read_text() != files[rel]:
            print(f"REFUSED: {rel} exists with different content (A2 files are written once)", file=sys.stderr)
            return 3
    build_x2.write(files, A2)
    for name in COPIED:
        shutil.copyfile(X2 / a.platform / name, A2 / a.platform / name)
    print(f"{len(files)} files, sha256 {build_x2.digest(files)} (+ byte copies of {', '.join(COPIED)})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
