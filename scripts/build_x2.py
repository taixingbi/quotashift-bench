"""Protocol X2 deterministic scenario generator (docs/PROTOCOL_X2_DRAFT.md rev 2, sections 5-7). NOT frozen.

Generated YAMLs are a pure function of (platform, phase, inputs). Nothing is random here; schedules are drawn later by
the harness from each scenario's seed + isolation salt. There is NO anchor: every input is the platform's own.

    calA   from the platform's own Phase-1 isolated S-request hold time (QUALIFICATION.json "hold_s_mean"):
           6 rates whose PREDICTED control slot demand is 0.30 .. 0.90; traces frozen BEFORE any calA run
    main   at the platform's own selected low rate (RATES.json from choose_low); traces frozen BEFORE any main run

    uv run python scripts/build_x2.py calA --platform g0m0 --hold-s 1.35 --out experiments/x2
    uv run python scripts/build_x2.py main --platform g0m0 --rates experiments/x2/g0m0/RATES.json --out experiments/x2

Reuses the frozen v5 shapes and request-count rule (scripts/build_v5.py, imported unchanged). protocol_version 5, i.e.
every v5 harness gate; the X2 identity is the `x2_` scenario prefix, the `x2-` isolation salt and the header.
"""

